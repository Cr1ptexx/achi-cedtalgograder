// Copies the solutions you wrote in the practice folder into my-solutions/ for the portfolio.
//   node scripts/sync-solutions.mjs [practice dir] [--force]
// Only problems whose solution (a) differs from the empty starter and (b) passes every local test are copied,
// so the repo never contains half-finished or wrong code. Existing copies are not overwritten unless --force.
// Each file gets a header with blanks (Idea / Complexity / Pitfalls) for YOU to write your own explanation.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const args = process.argv.slice(2);
const force = args.includes('--force');
const practice = resolve(args.find((a) => !a.startsWith('--')) ?? 'D:/DataAlgo/algo');
const out = resolve('my-solutions');
const judge = join(practice, 'tools/judge.mjs');
if (!existsSync(judge)) { console.error(`ไม่พบ ${judge} (รัน scripts/make-practice.mjs ก่อน)`); process.exit(1); }

const catalog = [...readFileSync('src/data/catalog.ts', 'utf8').matchAll(/\{ code: '([^']+)', title: '([^']+)', graderId: (\d+), chapter: '([^']+)'/g)]
  .map((m) => ({ code: m[1], title: m[2], graderId: +m[3], chapter: m[4] }));

const CH = {
  'brute-force': '01-brute-force', sorting: '02-sorting', recursion: '03-recursion', 'divide-conquer': '04-divide-conquer', dp: '05-dp',
  greedy: '06-greedy', graph: '07-graph', 'shortest-path': '08-shortest-path', search: '09-search', exam: '10-exam-past-papers',
};
const strip = (s) => s.replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, '');
const EMPTY = strip('#include <bits/stdc++.h> using namespace std; int main() { ios::sync_with_stdio(false); cin.tie(nullptr); return 0; }');

const header = (p) => `/*
 * ${p.title}  (${p.code}, grader #${p.graderId})
 * Chapter    : ${CH[p.chapter].slice(3)}
 *
 * Idea       :
 * Complexity :
 * Pitfalls   :
 */

`;
const HEADER_RE = /^\/\*[\s\S]*?\*\/\n\n/;
const STARTER_HEADER_RE = /^(\/\/.*\n)+\n?/;
const oneLine = (file) => { const m = readFileSync(file, 'utf8').match(/^ \* Idea\s*:[ \t]*(.*)$/m); return m ? m[1].trim() : ''; };

const rows = [];
let copied = 0, kept = 0, skippedEmpty = 0, migrated = 0;
const failing = [], newer = [];
for (const p of catalog) {
  const src = join(practice, CH[p.chapter], p.code, `${p.code}.cpp`);
  if (!existsSync(src)) continue;
  const code = readFileSync(src, 'utf8');
  if (strip(code) === EMPTY) { skippedEmpty++; continue; }

  const dest = join(out, CH[p.chapter], `${p.code}.cpp`);
  const body = code.replace(STARTER_HEADER_RE, '');
  if (existsSync(dest) && !force) {
    const cur = readFileSync(dest, 'utf8');
    if (cur.includes('Status  : passes all local tests')) { // header generated by an older version of this script
      writeFileSync(dest, header(p) + cur.replace(HEADER_RE, '')); migrated++;
    } else if (cur.replace(HEADER_RE, '').trim() !== body.trim()) newer.push(p.code);
    kept++; rows.push(p);
    continue;
  }
  const r = spawnSync('node', [judge, join(practice, CH[p.chapter], p.code)], { encoding: 'utf8', timeout: 180000 });
  if (r.status !== 0) { failing.push(p.code); continue; }
  mkdirSync(join(out, CH[p.chapter]), { recursive: true });
  const prev = existsSync(dest) ? readFileSync(dest, 'utf8').match(HEADER_RE)?.[0] : null;   // --force keeps the explanation you wrote
  writeFileSync(dest, (prev ?? header(p)) + body);
  copied++; rows.push(p);
}

// README table: problem + the one-line idea you wrote in each file's header (empty until you fill it in)
let table = '';
for (const ch of Object.keys(CH)) {
  const list = rows.filter((p) => p.chapter === ch);
  if (!list.length) continue;
  table += `\n### ${CH[ch].slice(0, 2)} ${CH[ch].slice(3)}\n\n| Problem | My idea |\n|---|---|\n`;
  for (const p of list) table += `| [${p.title}](${CH[ch]}/${p.code}.cpp) | ${oneLine(join(out, CH[ch], `${p.code}.cpp`))} |\n`;
}
const readmePath = join(out, 'README.md');
if (existsSync(readmePath)) {
  const old = readFileSync(readmePath, 'utf8');
  const a = old.indexOf('<!-- solutions:start -->'), b = old.indexOf('<!-- solutions:end -->');
  if (a >= 0 && b > a) writeFileSync(readmePath, `${old.slice(0, a)}<!-- solutions:start -->\n${table}\n${old.slice(b)}`);
}
console.log(`คัดลอกใหม่ ${copied} ข้อ · มีอยู่แล้ว ${kept} ข้อ (ล้างหัวไฟล์เก่า ${migrated}) · ยังเป็นไฟล์เปล่า ${skippedEmpty} ข้อ`);
if (failing.length) console.log(`ข้ามเพราะยังผ่านเทสไม่ครบ/คอมไพล์ไม่ผ่าน: ${failing.join(', ')}`);
if (newer.length) console.log(`โค้ดในโฟลเดอร์ฝึกใหม่กว่าสำเนาที่นี่ (ใช้ --force เพื่อทับ โดยคงคำอธิบายที่คุณเขียนไว้): ${newer.join(', ')}`);
